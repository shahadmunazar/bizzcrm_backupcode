    <script>
        $(document).ready(function() {
            const boxSlug = '{{ request()->route("box_slug") }}';
            let startDate = '';
            let endDate = '';
            let currentSort = 'desc';
            let searchQuery = '';
            
            function loadAllAssignments() {
                let url = '/' + boxSlug + '/fieldstracking/target-api/assignments';
                let params = [];
                if (startDate && endDate) {
                    params.push('start_date=' + startDate + '&end_date=' + endDate);
                }
                params.push('order=' + currentSort);
                
                if (searchQuery) {
                    params.push('search=' + encodeURIComponent(searchQuery));
                }

                if (params.length > 0) {
                    url += '?' + params.join('&');
                }

                $.get(url, function(data) {
                    let tbody = $('#team_targets_tbody');
                    tbody.empty();

                    if (data.length === 0) {
                        tbody.append('<tr><td colspan="8" class="text-center">No targets assigned to anyone yet.</td></tr>');
                        return;
                    }

                    data.forEach(assignment => {
                        let score = assignment.performance ? assignment.performance.achievement_percentage : null;
                        let scoreDisplay = score !== null ? parseFloat(score).toFixed(2) + '%' : '<span class="text-muted">Not calculated</span>';
                        
                        let metricsDisplay = '-';
                        if (assignment.template.metrics && assignment.template.metrics.length > 0) {
                            let mArr = [];
                            assignment.template.metrics.forEach(m => {
                                let actualObj = assignment.actuals ? assignment.actuals.find(a => a.metric_id === m.id) : null;
                                let actualVal = actualObj ? actualObj.actual_value : 0;
                                mArr.push(`<span class="badge badge-pill badge-info me-1 mb-1">${m.metric_name}: ${actualVal} / ${m.target_value}</span>`);
                            });
                            metricsDisplay = mArr.join('');
                        }
                        
                        let assignedTo = 'Unknown';
                        if (assignment.box_user_id && assignment.box_user) {
                            assignedTo = (assignment.box_user.first_name || '') + ' ' + (assignment.box_user.last_name || '');
                            if (!assignedTo.trim() && assignment.box_user.user) {
                                assignedTo = assignment.box_user.user.name;
                            }
                            assignedTo += ' <small class="text-muted">(Employee)</small>';
                        } else if (assignment.team_id) {
                            assignedTo = 'Team ID: ' + assignment.team_id;
                        } else if (assignment.department_id) {
                            assignedTo = 'Department ID: ' + assignment.department_id;
                        }

                        let row = `
                            <tr>
                                <td><label class="checkboxs"><input type="checkbox"><span class="checkmarks"></span></label></td>
                                <td>${assignment.template.name}</td>
                                <td>${assignedTo}</td>
                                <td>${assignment.template.frequency}</td>
                                <td>${scoreDisplay}</td>
                                <td>${metricsDisplay}</td>
                                <td><span class="badge badge-pill bg-success">${assignment.status}</span></td>
                                <td>
                                    <div class="dropdown table-action">
                                        <a href="#" class="action-icon " data-bs-toggle="dropdown" aria-expanded="false">
                                            <i class="fa fa-ellipsis-v"></i>
                                        </a>
                                        <div class="dropdown-menu dropdown-menu-right">
                                            <a class="dropdown-item" href="#">
                                                <i class="ti ti-eye text-blue"></i> View Details
                                            </a>
                                        </div>
                                    </div>
                                </td>
                            </tr>
                        `;
                        tbody.append(row);
                    });
                });
            }

